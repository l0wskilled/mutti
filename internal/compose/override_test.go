package compose

import (
	"encoding/json"
	"testing"

	"github.com/google/go-cmp/cmp"
)

func TestRenderOverride(t *testing.T) {
	m := &Model{Services: map[string]Service{
		"web":    {Ports: []Port{{Target: 80, Published: "8080", Protocol: "tcp"}, {Target: 443}}},
		"db":     {Ports: []Port{{Target: 5432, HostIP: "0.0.0.0", Protocol: "tcp"}}},
		"worker": {},
		"dns":    {Ports: []Port{{Target: 53, Protocol: "udp"}}},
	}}
	want := `# Generated by mutti up, which rewrites it every time. Do not edit.
services:
  "db":
    ports: !override
      - target: 5432
        host_ip: 127.0.0.1
        protocol: tcp
  "dns":
    ports: !override
      - target: 53
        host_ip: 127.0.0.1
        protocol: udp
  "web":
    ports: !override
      - target: 80
        host_ip: 127.0.0.1
        protocol: tcp
      - target: 443
        host_ip: 127.0.0.1
        protocol: tcp
`
	if diff := cmp.Diff(want, string(RenderOverride(m, Override{}))); diff != "" {
		t.Errorf("override (-want +got):\n%s", diff)
	}
}

func TestRenderOverrideWithoutPorts(t *testing.T) {
	m := &Model{Services: map[string]Service{"worker": {}}}
	if got := RenderOverride(m, Override{}); got != nil {
		t.Fatalf("want nil, got %q", got)
	}
	// The project's name alone makes an override.
	want := "# Generated by mutti up, which rewrites it every time. Do not edit.\nname: \"shop-x\"\n"
	if got := string(RenderOverride(m, Override{Name: "shop-x"})); got != want {
		t.Fatalf("name only: %q", got)
	}
}

func TestRenderOverrideWithNetworkAndLabels(t *testing.T) {
	m := &Model{Services: map[string]Service{
		"api":  {Networks: map[string]json.RawMessage{"default": nil, "back": nil}},
		"host": {NetworkMode: "host"},
	}}
	got := RenderOverride(m, Override{
		Network:      "mutti-shop",
		CommonLabels: map[string]string{"mutti.instance": "shop"},
		Labels:       map[string]map[string]string{"api": {"mutti.route.port": "80", "mutti.instance": "override-wins"}},
	})
	want := `# Generated by mutti up, which rewrites it every time. Do not edit.
services:
  "api":
    networks:
      "back": {}
      "default": {}
      mutti-ingress: {}
    labels:
      "mutti.instance": "override-wins"
      "mutti.route.port": "80"
  "host":
    labels:
      "mutti.instance": "shop"
networks:
  mutti-ingress:
    name: "mutti-shop"
    external: true
`
	if diff := cmp.Diff(want, string(got)); diff != "" {
		t.Errorf("(-want +got):\n%s", diff)
	}
}

func TestRenderOverrideWithFixedPorts(t *testing.T) {
	m := &Model{Services: map[string]Service{
		"db": {Ports: []Port{{Target: 5432, Protocol: "tcp"}, {Target: 53, Protocol: "udp"}}},
	}}
	got := RenderOverride(m, Override{FixedPorts: map[string]map[uint16]uint16{"db": {5432: 25432, 9187: 29187, 53: 20053}}})
	want := `# Generated by mutti up, which rewrites it every time. Do not edit.
services:
  "db":
    ports: !override
      - target: 5432
        host_ip: 127.0.0.1
        protocol: tcp
        published: "25432"
      - target: 53
        host_ip: 127.0.0.1
        protocol: udp
      - target: 53
        host_ip: 127.0.0.1
        protocol: tcp
        published: "20053"
      - target: 9187
        host_ip: 127.0.0.1
        protocol: tcp
        published: "29187"
`
	if diff := cmp.Diff(want, string(got)); diff != "" {
		t.Errorf("(-want +got):\n%s", diff)
	}
}
