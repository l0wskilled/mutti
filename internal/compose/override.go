package compose

import (
	"fmt"
	"maps"
	"slices"
	"strconv"
	"strings"
)

// LoopbackIP is where mutti publishes ports, so dev environments are not reachable from the LAN.
const LoopbackIP = "127.0.0.1"

// IngressNetwork is the key of mutti's ingress network in the override.
const IngressNetwork = "mutti-ingress"

// Override is what mutti adds on top of the user's Compose files.
type Override struct {
	// Name is the Compose project name, so docker compose run by hand with these files, without
	// mutti's flags, works on the same project.
	Name string
	// Network is the name of the instance's ingress network, which mutti creates and the router
	// joins. Every service that can join networks is attached to it. Empty means none.
	Network string
	// Labels are extra container labels, per service.
	Labels map[string]map[string]string
	// CommonLabels are added to every service.
	CommonLabels map[string]string
	// FixedPorts publish container ports on fixed host ports: service -> container port -> host
	// port. Ports the service does not publish yet are added.
	FixedPorts map[string]map[uint16]uint16
	// Binds replace bind mounts of a service, matched by target, e.g. with sources translated to
	// paths on the Docker host.
	Binds map[string][]VolumeMount
}

// RenderOverride returns the Compose override for m, or nil if nothing needs overriding.
//   - The project gets its name.
//   - Published ports move to random host ports on loopback, so two instances of one project
//     never fight over a host port; FixedPorts get their fixed one.
//   - Services join the ingress network next to the networks they already have.
//   - Labels are added.
func RenderOverride(m *Model, o Override) []byte {
	var b strings.Builder
	for _, name := range m.ServiceNames() {
		svc := m.Services[name]
		var lines []string
		fixed := o.FixedPorts[name]
		ports := slices.Clone(svc.Ports)
		for _, target := range slices.Sorted(maps.Keys(fixed)) {
			if !slices.ContainsFunc(ports, func(p Port) bool { return p.Target == target && p.Protocol != "udp" }) {
				ports = append(ports, Port{Target: target, Protocol: "tcp"})
			}
		}
		if len(ports) > 0 {
			lines = append(lines, "    ports: !override")
			for _, p := range ports {
				proto := p.Protocol
				if proto == "" {
					proto = "tcp"
				}
				line := fmt.Sprintf("      - target: %d\n        host_ip: %s\n        protocol: %s", p.Target, LoopbackIP, proto)
				if host, ok := fixed[p.Target]; ok && proto == "tcp" {
					line += fmt.Sprintf("\n        published: \"%d\"", host)
				}
				lines = append(lines, line)
			}
		}
		if o.Network != "" && svc.NetworkMode == "" {
			lines = append(lines, "    networks:")
			for _, n := range slices.Sorted(maps.Keys(svc.Networks)) {
				lines = append(lines, fmt.Sprintf("      %s: {}", strconv.Quote(n)))
			}
			lines = append(lines, fmt.Sprintf("      %s: {}", IngressNetwork))
		}
		if binds := o.Binds[name]; len(binds) > 0 {
			lines = append(lines, "    volumes:")
			for _, v := range binds {
				line := fmt.Sprintf("      - type: bind\n        source: %s\n        target: %s", strconv.Quote(v.Source), strconv.Quote(v.Target))
				if v.ReadOnly {
					line += "\n        read_only: true"
				}
				if b := v.Bind; b != nil && (b.CreateHostPath || b.Propagation != "" || b.SELinux != "") {
					line += "\n        bind:"
					if b.CreateHostPath {
						line += "\n          create_host_path: true"
					}
					if b.Propagation != "" {
						line += "\n          propagation: " + strconv.Quote(b.Propagation)
					}
					if b.SELinux != "" {
						line += "\n          selinux: " + strconv.Quote(b.SELinux)
					}
				}
				lines = append(lines, line)
			}
		}
		labels := maps.Clone(o.CommonLabels)
		if labels == nil {
			labels = map[string]string{}
		}
		maps.Copy(labels, o.Labels[name])
		if len(labels) > 0 {
			lines = append(lines, "    labels:")
			for _, k := range slices.Sorted(maps.Keys(labels)) {
				lines = append(lines, fmt.Sprintf("      %s: %s", strconv.Quote(k), strconv.Quote(labels[k])))
			}
		}
		if len(lines) > 0 {
			fmt.Fprintf(&b, "  %s:\n%s\n", strconv.Quote(name), strings.Join(lines, "\n"))
		}
	}
	if b.Len() == 0 && o.Name == "" {
		return nil
	}
	out := "# Generated by mutti up, which rewrites it every time. Do not edit.\n"
	if o.Name != "" {
		out += fmt.Sprintf("name: %s\n", strconv.Quote(o.Name))
	}
	if b.Len() > 0 {
		out += "services:\n" + b.String()
	}
	if o.Network != "" {
		out += fmt.Sprintf("networks:\n  %s:\n    name: %s\n    external: true\n", IngressNetwork, strconv.Quote(o.Network))
	}
	return []byte(out)
}
