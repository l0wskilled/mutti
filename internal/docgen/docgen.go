// Package docgen generates the reference documentation from the code, so it cannot drift: the
// CLI reference from the cobra commands, and the x-mutti reference and JSON Schemas from the
// configuration structs and their comments.
package docgen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/invopop/jsonschema"
	"github.com/spf13/cobra"
	"github.com/spf13/cobra/doc"

	"github.com/l0wskilled/mutti/internal/project"
)

// ComposeSpecSchema is the official Compose file schema the combined schema extends.
const ComposeSpecSchema = "https://raw.githubusercontent.com/compose-spec/compose-spec/main/schema/compose-spec.json"

// Paths of the generated files, relative to the docs directory.
const (
	CLIDir         = "reference/cli"
	XMuttiSchema   = "reference/x-mutti.schema.json"
	ComposeSchema  = "reference/compose-with-mutti.schema.json"
	XMuttiMarkdown = "reference/x-mutti.md"
)

// Generate writes the reference documentation into docsDir. repoRoot is where the module's
// sources are, for the comments that become descriptions.
func Generate(repoRoot, docsDir string, root *cobra.Command) error {
	cliDir := filepath.Join(docsDir, CLIDir)
	if err := os.RemoveAll(cliDir); err != nil {
		return err
	}
	if err := os.MkdirAll(cliDir, 0o755); err != nil { //nolint:gosec // documentation
		return err
	}
	root.DisableAutoGenTag = true // no dates: generated files only change with the code
	if err := doc.GenMarkdownTree(root, cliDir); err != nil {
		return err
	}

	s, err := Schema(repoRoot)
	if err != nil {
		return err
	}
	files := map[string][]byte{
		XMuttiSchema:   encode(s),
		ComposeSchema:  encode(composeWithMutti(s)),
		XMuttiMarkdown: Markdown(s),
	}
	for name, content := range files {
		if err := os.WriteFile(filepath.Join(docsDir, name), content, 0o644); err != nil { //nolint:gosec // documentation
			return err
		}
	}
	return nil
}

// Schema returns the JSON Schema of the x-mutti block, with descriptions from the Go comments
// of the configuration structs.
func Schema(repoRoot string) (*jsonschema.Schema, error) {
	r := &jsonschema.Reflector{
		DoNotReference:             true,
		ExpandedStruct:             true,
		RequiredFromJSONSchemaTags: true, // every key is optional
	}
	if err := r.AddGoComments("github.com/l0wskilled/mutti", filepath.Join(repoRoot, "internal", "project")); err != nil {
		return nil, fmt.Errorf("read comments: %w", err)
	}
	s := r.Reflect(&project.Config{})
	s.Version = "https://json-schema.org/draft/2020-12/schema"
	s.ID = "https://github.com/l0wskilled/mutti/x-mutti.schema.json"
	s.Title = "x-mutti"
	s.Description = "mutti's settings in a Compose file. Every key is optional."
	return s, nil
}

// composeWithMutti extends the official Compose schema by x-mutti, for editors that should
// complete and check the whole file.
func composeWithMutti(xmutti *jsonschema.Schema) map[string]any {
	return map[string]any{
		"$schema":     "https://json-schema.org/draft/2020-12/schema",
		"$id":         "https://github.com/l0wskilled/mutti/compose-with-mutti.schema.json",
		"title":       "Compose file with x-mutti",
		"description": "The Compose file schema plus mutti's x-mutti block.",
		"allOf": []any{
			map[string]any{"$ref": ComposeSpecSchema},
			map[string]any{"properties": map[string]any{"x-mutti": xmutti}},
		},
	}
}

func encode(v any) []byte {
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	_ = enc.Encode(v) // plain values, cannot fail
	return b.Bytes()
}

// Markdown renders the x-mutti reference: one row per key, nested keys with dotted paths.
func Markdown(s *jsonschema.Schema) []byte {
	var b strings.Builder
	b.WriteString("# x-mutti reference\n\n")
	b.WriteString("<!-- Generated by `make docs` from internal/project. Do not edit. -->\n\n")
	b.WriteString(s.Description + "\n\n")
	b.WriteString("| Key | Type | Description |\n|---|---|---|\n")
	rows(&b, "", s)
	return []byte(b.String())
}

func rows(b *strings.Builder, prefix string, s *jsonschema.Schema) {
	if s.Properties == nil {
		return
	}
	for pair := s.Properties.Oldest(); pair != nil; pair = pair.Next() {
		key, prop := pair.Key, pair.Value
		path := key
		if prefix != "" {
			path = prefix + "." + key
		}
		fmt.Fprintf(b, "| `%s` | %s | %s |\n", path, typeOf(prop), oneLine(prop.Description))
		rows(b, path, prop)
		if prop.Items != nil {
			rows(b, path+"[]", prop.Items)
		}
		if prop.AdditionalProperties != nil {
			rows(b, path+".<name>", prop.AdditionalProperties)
		}
	}
}

func typeOf(s *jsonschema.Schema) string {
	switch {
	case s.Type == "array" && s.Items != nil:
		return "list of " + typeOf(s.Items)
	case s.Type == "object" && s.AdditionalProperties != nil && s.Properties == nil:
		return "map of " + typeOf(s.AdditionalProperties)
	default:
		return s.Type
	}
}

func oneLine(s string) string {
	return strings.Join(strings.Fields(s), " ")
}
